interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: keyof typeof translations['en']) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key) => translations.en[key] || key
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const stored = localStorage.getItem('iptv_language') as Language;
      if (stored && ['en', 'es', 'pt', 'fr'].includes(stored)) return stored;

      // Smart system language detection with LG webOS TV support
      const palmLocale = (window as any).PalmSystem?.locale || (window as any).PalmSystem?.country || '';
      const navLocale = navigator.language || (navigator as any).userLanguage || '';
      const sysLang = (palmLocale || navLocale || '').toLowerCase();
      if (sysLang.startsWith('es')) return 'es';
      if (sysLang.startsWith('pt')) return 'pt';
      if (sysLang.startsWith('fr')) return 'fr';

      // Default to English for international LG QA certification
      return 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('iptv_language', lang);
    } catch {}
  };

  const t = (key: keyof typeof translations['en']): string => {
    const langDict = translations[language] || translations.en;
    return (langDict as any)[key] || (translations.en as any)[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useTranslation = () => useContext(LanguageContext);
